"""`scrubgpt-codegen`: the contract models → JSON Schema → TypeScript (plan §4.1, §4.5; D-031).

    scrubgpt-codegen [--out DIR] [--schema-only]

Writes, under `DIR` (default: `contracts/`):
- `schema/<Model>.schema.json`: one JSON Schema (draft 2020-12, Pydantic `mode="serialization"`,
  the wire format) per top-level model: every contract file, the Decision Record, `ApiError`,
  and each Brain API request and response.
- `ts/contracts.ts`: TypeScript types for all of them, from one bundled schema, via
  `npx json-schema-to-typescript@<JSON2TS_VERSION>` (pinned). v1.0 fields have no defaults, so
  they are required keys; MINOR-added `T | None = None` fields come out optional (`?`).

Both folders are generated: never edit them by hand. CI re-runs codegen and fails if they are
stale. Output is byte-for-byte reproducible (LF line endings, stable order).
"""

import argparse
import json
import shutil
import subprocess
import sys
import tempfile
from collections.abc import Iterable
from pathlib import Path
from typing import Any

from pydantic import BaseModel
from pydantic.json_schema import models_json_schema

from scrubgpt_contracts.models.brain_api import ENDPOINTS
from scrubgpt_contracts.models.case_package import JSON_FILES
from scrubgpt_contracts.models.common import CONTRACT_VERSION, ApiError
from scrubgpt_contracts.models.decision_record import DecisionRecord, DecisionRecordDraft
from scrubgpt_contracts.models.reference import ProcedureReference

JSON2TS_VERSION = "15.0.4"
DEFAULT_OUT = Path(__file__).resolve().parents[2]
SCHEMA_DIALECT = "https://json-schema.org/draft/2020-12/schema"
BUNDLE_TITLE = "ScrubGPTContracts"
TS_FILE = "contracts.ts"
BANNER = (
    "/* Generated by scrubgpt-codegen from contracts/scrubgpt_contracts/models "
    f"(contract {CONTRACT_VERSION}). Do not edit by hand: run `uv run scrubgpt-codegen`. */"
)


class CodegenError(Exception):
    """Codegen could not finish (exit code 2)."""


def top_level_models() -> list[type[BaseModel]]:
    """Every model that is a whole document on disk or on the wire, without duplicates."""
    models: list[type[BaseModel]] = [
        *JSON_FILES.values(),
        ProcedureReference,
        DecisionRecord,
        DecisionRecordDraft,
        ApiError,
    ]
    for endpoint in ENDPOINTS.values():
        if endpoint.request is not None:
            models.append(endpoint.request)
        models.append(endpoint.response)
    unique = list(dict.fromkeys(models))
    names = [model.__name__ for model in unique]
    if len(set(names)) != len(names):
        raise CodegenError(f"two top-level models share a name: {sorted(names)}")
    return unique


def _strip_titles(node: Any, *, keep: bool) -> Any:
    """Drop the `title` Pydantic puts on every property, so json-schema-to-typescript names only
    real types (models and enums), not one alias per field."""
    if isinstance(node, dict):
        out = {}
        for key, value in node.items():
            if key == "title" and not keep:
                continue
            if key in ("$defs", "properties", "patternProperties"):
                # Keys here are names, not schemas: keep titles on $defs entries only.
                out[key] = {
                    name: _strip_titles(sub, keep=key == "$defs") for name, sub in value.items()
                }
            else:
                out[key] = _strip_titles(value, keep=False)
        if "$ref" in out and len(out) > 1:
            # A `$ref` with siblings (a field's description) would become a new numbered type
            # (`Lang1`, `Bilingual2`, …); `allOf` keeps the description on the field instead.
            ref = out.pop("$ref")
            out = {"allOf": [{"$ref": ref}], **out}
        return out
    if isinstance(node, list):
        return [_strip_titles(item, keep=False) for item in node]
    return node


def model_schema(model: type[BaseModel]) -> dict[str, Any]:
    """The serialization schema of one model, self-contained (its own `$defs`)."""
    schema = model.model_json_schema(mode="serialization")
    return {"$schema": SCHEMA_DIALECT, **_strip_titles(schema, keep=True)}


def bundle_schema(models: Iterable[type[BaseModel]]) -> dict[str, Any]:
    """One schema whose `$defs` hold every model once; the root lists the top-level models."""
    models = list(models)
    refs, bundle = models_json_schema(
        [(model, "serialization") for model in models], ref_template="#/$defs/{model}"
    )
    properties = {model.__name__: refs[(model, "serialization")] for model in models}
    root = {
        "$schema": SCHEMA_DIALECT,
        "title": BUNDLE_TITLE,
        "description": "Every top-level ScrubGPT contract model (generated).",
        "type": "object",
        "properties": properties,
        "required": list(properties),
        "additionalProperties": False,
        "$defs": bundle.get("$defs", {}),
    }
    return _strip_titles(root, keep=True)


def _json(data: Any) -> str:
    return json.dumps(data, ensure_ascii=False, indent=2) + "\n"


def _write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")


def _clear(folder: Path, pattern: str) -> None:
    """Remove earlier generated files, so a deleted model leaves no stale file behind."""
    for path in folder.glob(pattern):
        path.unlink()


def write_schemas(out: Path, models: list[type[BaseModel]]) -> list[Path]:
    folder = out / "schema"
    folder.mkdir(parents=True, exist_ok=True)
    _clear(folder, "*.schema.json")
    written = []
    for model in models:
        path = folder / f"{model.__name__}.schema.json"
        _write(path, _json(model_schema(model)))
        written.append(path)
    return written


def _npx() -> str:
    npx = shutil.which("npx")  # finds npx.cmd on Windows through PATHEXT
    if npx is None:
        raise CodegenError("npx not found: install Node (see .nvmrc), or use --schema-only")
    return npx


def write_typescript(out: Path, models: list[type[BaseModel]]) -> Path:
    target = out / "ts" / TS_FILE
    with tempfile.TemporaryDirectory(prefix="scrubgpt-codegen-") as tmp:
        source = Path(tmp) / "contracts.schema.json"
        generated = Path(tmp) / TS_FILE
        _write(source, _json(bundle_schema(models)))
        command = [
            _npx(),
            "--yes",
            f"json-schema-to-typescript@{JSON2TS_VERSION}",
            "--input",
            str(source),
            "--output",
            str(generated),
            "--unreachableDefinitions",
            "--no-additionalProperties",
            "--bannerComment",
            BANNER,
        ]
        try:
            result = subprocess.run(
                command, capture_output=True, text=True, encoding="utf-8", timeout=300
            )
        except (OSError, subprocess.SubprocessError) as exc:
            raise CodegenError(f"json-schema-to-typescript failed to run: {exc}") from None
        if result.returncode != 0 or not generated.is_file():
            detail = (result.stderr or result.stdout).strip()[-2000:]
            raise CodegenError(f"json-schema-to-typescript failed:\n{detail}")
        text = generated.read_text(encoding="utf-8").replace("\r\n", "\n").rstrip("\n") + "\n"
    target.parent.mkdir(parents=True, exist_ok=True)
    _clear(target.parent, "*.ts")
    _write(target, text)
    return target


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="scrubgpt-codegen",
        description="Generate schema/ (JSON Schema) and ts/ (TypeScript) from the contract models",
    )
    parser.add_argument(
        "--out",
        type=Path,
        default=DEFAULT_OUT,
        help="folder that receives schema/ and ts/ (default: contracts/)",
    )
    parser.add_argument(
        "--schema-only", action="store_true", help="write schema/ only (no Node needed)"
    )
    args = parser.parse_args(argv)
    try:
        models = top_level_models()
        schemas = write_schemas(args.out, models)
        print(f"scrubgpt-codegen: {len(schemas)} schemas → {args.out / 'schema'}")
        if not args.schema_only:
            ts = write_typescript(args.out, models)
            print(f"scrubgpt-codegen: TypeScript → {ts}")
    except CodegenError as exc:
        print(f"scrubgpt-codegen: {exc}", file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
